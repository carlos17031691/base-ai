import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { aiSync } from "../sync.js";

function fixture(): string {
  const d = mkdtempSync(join(tmpdir(), "base-ai-"));
  mkdirSync(join(d, ".ai/skills/adr"), { recursive: true });
  writeFileSync(join(d, ".ai/rules.md"), "# Rules\n- rule");
  writeFileSync(join(d, ".ai/skills/adr/skill.md"), "---\nid: adr\ndescription: Creates ADRs\n---\nADR body");
  return d;
}

test("generates artefacts for all agents", () => {
  const d = fixture();
  aiSync(d);
  for (const f of ["AGENTS.md", "CLAUDE.md", ".agents/skills/adr/SKILL.md", ".cursor/rules/adr.mdc", ".github/prompts/adr.prompt.md", ".claude/commands/adr.md"]) {
    assert.ok(existsSync(join(d, f)), f);
  }
  assert.match(readFileSync(join(d, ".agents/skills/adr/SKILL.md"), "utf8"), /^---\nname: "adr"/);
});

test("is idempotent and doctor detects drift", () => {
  const d = fixture();
  aiSync(d);
  assert.equal(aiSync(d, true)[0].written.length, 0);
  writeFileSync(join(d, ".ai/rules.md"), "# Changed");
  assert.ok(aiSync(d, true)[0].written.length > 0);
});

test("removes stale artefacts", () => {
  const d = fixture();
  aiSync(d);
  rmSync(join(d, ".ai/skills/adr"), { recursive: true });
  aiSync(d);
  assert.ok(!existsSync(join(d, ".agents/skills/adr/SKILL.md")));
});

test("does not overwrite files not generated by base-ai", () => {
  const d = fixture();
  writeFileSync(join(d, "CLAUDE.md"), "manual");
  assert.throws(() => aiSync(d), /not generated/);
});

test("services inherit and extend rules", () => {
  const d = fixture();
  writeFileSync(join(d, "services.yaml"), "version: 1\nservices:\n  - name: api\n");
  mkdirSync(join(d, "src/api/.ai"), { recursive: true });
  writeFileSync(join(d, "src/api/.ai/rules.md"), "Local rule");
  aiSync(d);
  const agents = readFileSync(join(d, "src/api/AGENTS.md"), "utf8");
  assert.match(agents, /# Rules[\s\S]*Local rule/);
});

// --- Role definitions exported to services (BASE-046-D1) ---

const ROLE = "---\nname: qa\ndescription: Verifies criteria\ntools: Read, Bash\n---\n\n# QA agent\n\nBody text.\n";

function withService(svc = "name: api", cfg?: string): string {
  const d = fixture();
  mkdirSync(join(d, ".claude/agents"), { recursive: true });
  writeFileSync(join(d, ".claude/agents/qa.md"), ROLE);
  writeFileSync(join(d, "services.yaml"), `version: 1\nservices:\n  - ${svc}\n`);
  mkdirSync(join(d, "src/api"), { recursive: true });
  if (cfg) {
    mkdirSync(join(d, "src/api/.ai"), { recursive: true });
    writeFileSync(join(d, "src/api/.ai/config.yaml"), cfg);
  }
  return d;
}

test("exports root role definitions to services as generated files", () => {
  const d = withService();
  aiSync(d);
  const copy = readFileSync(join(d, "src/api/.claude/agents/qa.md"), "utf8");
  assert.equal(
    copy,
    "---\nname: qa\ndescription: Verifies criteria\ntools: Read, Bash\n---\n<!-- generated by base-ai: do not edit. Source: root .claude/agents/ -->\n\n# QA agent\n\nBody text.\n",
  );
  assert.equal(readFileSync(join(d, ".claude/agents/qa.md"), "utf8"), ROLE, "root source unchanged");
  const rootLock = JSON.parse(readFileSync(join(d, ".ai/generated.json"), "utf8")).files as string[];
  assert.ok(!rootLock.includes(".claude/agents/qa.md"), "root definition is not a generated artefact");
  const svcLock = JSON.parse(readFileSync(join(d, "src/api/.ai/generated.json"), "utf8")).files as string[];
  assert.ok(svcLock.includes(".claude/agents/qa.md"));
});

test("exports no role definitions to services with ai: none or without claude", () => {
  const none = withService("name: api\n    ai: none");
  aiSync(none);
  assert.ok(!existsSync(join(none, "src/api/.claude/agents/qa.md")));
  const noClaude = withService("name: api", "agents: [cursor]\n");
  aiSync(noClaude);
  assert.ok(!existsSync(join(noClaude, "src/api/.claude/agents/qa.md")));
});

test("detects drift and removes stale role definition copies", () => {
  const d = withService();
  aiSync(d);
  writeFileSync(join(d, ".claude/agents/qa.md"), ROLE.replace("Body text.", "Changed."));
  const svc = aiSync(d, true).find((r) => r.target.endsWith("api"));
  assert.deepEqual(svc?.written, [".claude/agents/qa.md"]);
  aiSync(d);
  rmSync(join(d, ".claude/agents/qa.md"));
  assert.deepEqual(aiSync(d, true).find((r) => r.target.endsWith("api"))?.removed, [".claude/agents/qa.md"]);
  aiSync(d);
  assert.ok(!existsSync(join(d, "src/api/.claude/agents/qa.md")));
});

test("refuses to overwrite a hand-written role definition in a service", () => {
  const d = withService();
  mkdirSync(join(d, "src/api/.claude/agents"), { recursive: true });
  writeFileSync(join(d, "src/api/.claude/agents/qa.md"), "hand-made");
  assert.throws(() => aiSync(d), (e: Error) => e.message.includes("src/api/.claude/agents/qa.md") && e.message.includes("root .claude/agents/"));
  assert.equal(readFileSync(join(d, "src/api/.claude/agents/qa.md"), "utf8"), "hand-made");
});

test("rejects invalid root role definitions, naming the file", () => {
  const cases: [string, string, RegExp][] = [
    ["qa.md", "# no frontmatter", /qa\.md: missing frontmatter/],
    ["qa.md", "---\nname: [unclosed\n---\nbody", /qa\.md: invalid frontmatter: /],
    ["qa.md", "---\ndescription: d\n---\nbody", /qa\.md: missing "name"/],
    ["qa.md", "---\nname: qa\n---\nbody", /qa\.md: missing "description"/],
    ["Bad.md", "---\nname: Bad\ndescription: d\n---\nbody", /Bad\.md: invalid name "Bad"/],
    ["qa.md", "---\nname: reviewer\ndescription: d\n---\nbody", /qa\.md: name "reviewer" does not match the file name "qa"/],
  ];
  for (const [file, text, re] of cases) {
    const d = withService();
    rmSync(join(d, ".claude/agents/qa.md"));
    writeFileSync(join(d, ".claude/agents", file), text);
    assert.throws(() => aiSync(d), re, file);
  }
});
