// --- Usage hook in .claude/settings.json (BASE-101-U2) ---

const SETTINGS = ".claude/settings.json";
const withHook = (d: string, hook: string) => writeFileSync(join(d, ".ai/config.yaml"), `usage:\n  hook: ${hook}\n`);
const settings = (d: string) => JSON.parse(readFileSync(join(d, SETTINGS), "utf8"));

test("sync writes the hook: SubagentStop and Stop run the CLI by path, user keys preserved, entries marked", () => {
  const d = fixture();
  mkdirSync(join(d, ".claude"), { recursive: true });
  const user = { permissions: { allow: ["Bash(ls)"] }, hooks: { Stop: [{ hooks: [{ type: "command", command: "echo done" }] }] } };
  writeFileSync(join(d, SETTINGS), JSON.stringify(user));
  withHook(d, "claude-code");
  const res = aiSync(d)[0];
  assert.ok(res.written.includes(SETTINGS));
  const s = settings(d);
  assert.deepEqual(s.permissions, user.permissions);
  assert.equal(s.hooks.Stop[0].hooks[0].command, "echo done");
  for (const event of ["SubagentStop", "Stop"]) {
    const cmd: string = s.hooks[event].at(-1).hooks[0].command;
    assert.match(cmd, /usage record/);
    assert.match(cmd, /\$CLAUDE_PROJECT_DIR/);
    assert.match(cmd, /^node "\$CLAUDE_PROJECT_DIR\/node_modules\/@carlos17031691\/base-ai\/dist\/index\.js"/);
    assert.doesNotMatch(cmd, /^base-ai /);
    assert.match(cmd, /# generated by base-ai$/);
  }
  const lock = readFileSync(join(d, ".ai/generated.json"), "utf8");
  assert.doesNotMatch(lock, /settings\.json/, "never in the lock");

  const again = aiSync(d)[0];
  assert.ok(again.unchanged.includes(SETTINGS) && !again.written.includes(SETTINGS), "second sync is a no-op");
  assert.equal(aiSync(d, true)[0].written.length, 0);
});

test("sync uses the in-tree CLI path in the base-ai repository", () => {
  const d = fixture();
  mkdirSync(join(d, "cli"), { recursive: true });
  writeFileSync(join(d, "cli/package.json"), JSON.stringify({ name: "@carlos17031691/base-ai" }));
  withHook(d, "claude-code");
  aiSync(d);
  assert.match(settings(d).hooks.Stop[0].hooks[0].command, /^node "\$CLAUDE_PROJECT_DIR\/cli\/dist\/index\.js" usage record/);
});

test("opt-out: none adds no hook and removes the generated one; absent usage changes nothing", () => {
  const d = fixture();
  aiSync(d);
  assert.ok(!existsSync(join(d, SETTINGS)), "absent usage: no file");
  withHook(d, "none");
  aiSync(d);
  assert.ok(!existsSync(join(d, SETTINGS)), "none: no file");

  withHook(d, "claude-code");
  aiSync(d);
  withHook(d, "none");
  assert.ok(aiSync(d)[0].removed.includes(SETTINGS));
  assert.ok(!existsSync(join(d, SETTINGS)), "only generated content: deleted");

  // A user's file survives the switch to none, with only the generated entries gone.
  const user = { env: { A: "1" } };
  writeFileSync(join(d, SETTINGS), JSON.stringify(user));
  withHook(d, "claude-code");
  aiSync(d);
  withHook(d, "none");
  aiSync(d);
  assert.deepEqual(settings(d), user);
  rmSync(join(d, ".ai/config.yaml"));
  const before = readFileSync(join(d, SETTINGS), "utf8");
  aiSync(d);
  assert.equal(readFileSync(join(d, SETTINGS), "utf8"), before, "absent usage leaves the user's file alone");
});

test("an invalid settings file throws and writes nothing; a bad usage.hook throws naming the key", () => {
  const d = fixture();
  mkdirSync(join(d, ".claude"), { recursive: true });
  writeFileSync(join(d, SETTINGS), "{oops");
  withHook(d, "claude-code");
  assert.throws(() => aiSync(d), /settings\.json is not valid JSON; fix it, then run: base-ai ai sync/);
  assert.equal(readFileSync(join(d, SETTINGS), "utf8"), "{oops");
  withHook(d, "sometimes");
  assert.throws(() => aiSync(d), /"usage\.hook" must be "claude-code" or "none"/);
  writeFileSync(join(d, ".ai/config.yaml"), "usage: yes\n");
  assert.throws(() => aiSync(d), /"usage\.hook" must be "claude-code" or "none"/);
});

test("review r1 M1: opted out or absent usage, a user's invalid settings file is left alone and sync succeeds", () => {
  for (const cfg of ["usage:\n  hook: none\n", null]) {
    const d = fixture();
    if (cfg !== null) writeFileSync(join(d, ".ai/config.yaml"), cfg);
    mkdirSync(join(d, ".claude"), { recursive: true });
    writeFileSync(join(d, SETTINGS), "{oops");
    const res = aiSync(d)[0];
    assert.ok(![...res.written, ...res.removed, ...res.unchanged].includes(SETTINGS), String(cfg));
    assert.equal(readFileSync(join(d, SETTINGS), "utf8"), "{oops");
  }
});

test("review r1 L4: an invalid settings file throws before any artefact is written", () => {
  const d = fixture();
  mkdirSync(join(d, ".claude"), { recursive: true });
  writeFileSync(join(d, SETTINGS), "{oops");
  withHook(d, "claude-code");
  assert.throws(() => aiSync(d), /settings\.json is not valid JSON/);
  assert.ok(!existsSync(join(d, "AGENTS.md")), "no artefact written");
  assert.ok(!existsSync(join(d, ".ai/generated.json")), "no lock written");
});
