test("init creates a clean, synced project without CI by default", () => {
  const dir = join(mkdtempSync(join(tmpdir(), "base-ai-init-")), "demo");
  init(dir);
  for (const f of [".ai/rules.md", ".ai/skills/adr/skill.md", "templates/service/README.md", "templates/service/.coderabbit.yaml", "templates/service/sonar-project.properties", ".coderabbit.yaml", "sonar-project.properties", "services.yaml", "AGENTS.md", ".agents/skills/adr/SKILL.md", ".git", ".githooks/pre-commit", "src/.gitkeep", "docs/architecture/adrs/.gitkeep"]) {
    assert.ok(existsSync(join(dir, f)), f);
  }
  assert.ok(!existsSync(join(dir, ".github/workflows")), "no CI by default");
  assert.ok(!existsSync(join(dir, "cli")), "does not copy the CLI");
  assert.ok(!existsSync(join(dir, "docs/architecture/adrs/ADR-0001-arquitectura-base-ai.md")), "does not copy base-ai ADRs");
  assert.equal(memoryList(dir).length, 0, "starts with clean project memory");
  assert.equal(aiSync(dir, true)[0].written.length, 0);
});

test("init carries the pipeline: role definitions, state-machine doc, task templates (BASE-046-D1)", () => {
  const dir = join(mkdtempSync(join(tmpdir(), "base-ai-init-")), "demo");
  init(dir);
  const tpl = templateRoot();
  const roles = readdirSync(join(tpl, ".claude/agents")).filter((f) => f.endsWith(".md")).sort();
  assert.deepEqual(roles, ["implementer.md", "improvement.md", "planner.md", "qa.md", "reviewer.md", "supervisor.md"]);
  // Reference files of a role (`.claude/agents/<role>/<name>.md`, BASE-079-T2), when the template has any.
  const refs = readdirSync(join(tpl, ".claude/agents"), { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .flatMap((e) => readdirSync(join(tpl, ".claude/agents", e.name)).filter((f) => f.endsWith(".md")).map((f) => `.claude/agents/${e.name}/${f}`));
  for (const f of [...roles.map((r) => `.claude/agents/${r}`), ...refs, "docs/task-state-machine.md"]) {
    assert.ok(readFileSync(join(dir, f)).equals(readFileSync(join(tpl, f))), `${f} byte-identical`);
  }
  for (const f of readdirSync(join(tpl, "templates/task"))) assert.ok(existsSync(join(dir, "templates/task", f)), f);
  assert.match(readFileSync(join(dir, ".claude/commands/adr.md"), "utf8"), /generated by base-ai/);
  assert.ok(!existsSync(join(dir, ".ai/tasks")), "no local task directories");
  assert.ok(!existsSync(join(dir, "docs/contract-testing-gate.md")), "no repository docs");
  assert.equal(
    readFileSync(join(dir, ".gitignore"), "utf8"),
    "src/*\n!src/.gitkeep\n.ai/context-index.json\n.ai/tasks/*\n!.ai/tasks/*/\n.ai/tasks/*/*\n!.ai/tasks/*/usage.jsonl\n.ai/usage/\n",
  );
  execFileSync("git", ["check-ignore", "-q", ".ai/tasks/X/status.json"], { cwd: dir });
  // usage.jsonl is versioned (BASE-101-U2): check-ignore exits 1 for it.
  assert.throws(() => execFileSync("git", ["check-ignore", "-q", ".ai/tasks/X/usage.jsonl"], { cwd: dir, stdio: "ignore" }));
  const svc = readFileSync(join(dir, "templates/service/.gitignore"), "utf8");
  assert.doesNotMatch(svc, /^\.ai\/tasks\/$/m);
  assert.match(svc, /^!\.ai\/tasks\/\*\/usage\.jsonl$/m);
});

test("init supports --ci github and gitlab", () => {
  const base = mkdtempSync(join(tmpdir(), "base-ai-init-"));
  const gh = join(base, "gh");
  const gl = join(base, "gl");
  init(gh, "github");
  init(gl, "gitlab");
  assert.ok(existsSync(join(gh, ".github/workflows/base-ai.yml")));
  assert.ok(existsSync(join(gl, ".gitlab-ci.yml")));
});

test("init rejects non-empty directories", () => {
  const dir = mkdtempSync(join(tmpdir(), "base-ai-init-"));
  writeFileSync(join(dir, "x"), "");
  assert.throws(() => init(dir), /not empty/);
});

test("init turns the usage hook off in the new project and writes no settings hook (BASE-101-U2)", () => {
  const dir = join(mkdtempSync(join(tmpdir(), "base-ai-init-")), "demo");
  init(dir);
  const cfg = parse(readFileSync(join(dir, ".ai/config.yaml"), "utf8"));
  assert.equal(cfg.usage.hook, "none");
  assert.equal(cfg.usage.pricing, undefined, "D4 H13: no maintainer prices in a new project");
  assert.equal(cfg.version, 1, "the rest of the config is kept");
  assert.ok(!existsSync(join(dir, ".claude/settings.json")));
});

test("D4 H13: the copied config loses usage.pricing in the same edit that turns the hook off; comments and other keys stay", () => {
  const dir = mkdtempSync(join(tmpdir(), "base-ai-init-cfg-"));
  mkdirSync(join(dir, ".ai"));
  writeFileSync(
    join(dir, ".ai/config.yaml"),
    "version: 1\n# usage comment kept\nusage:\n  hook: claude\n  pricing:\n    claude-opus-5-5: { input: 4, cache_write: 8, cache_read: 0.2, output: 20 }\n  keep: yes\n",
  );
  disableUsageHook(dir);
  const text = readFileSync(join(dir, ".ai/config.yaml"), "utf8");
  const cfg = parse(text);
  assert.deepEqual(cfg.usage, { hook: "none", keep: "yes" });
  assert.ok(text.includes("# usage comment kept"));
  disableUsageHook(join(dir, "missing"));
});
