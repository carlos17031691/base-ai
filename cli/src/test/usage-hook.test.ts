import { test } from "node:test";
import assert from "node:assert/strict";
import { hookCommand, hookState, isBaseAiRepo, mergeHook, parseSettings, removeHook, SettingsError } from "../usage-hook.js";

const CMD = hookCommand(true);
const OLD = 'node "$CLAUDE_PROJECT_DIR/old/index.js" usage record # generated by base-ai';
const gen = (command = CMD) => ({ hooks: [{ type: "command", command }] });
const userStop = { hooks: [{ type: "command", command: "echo done" }] };
const userPre = { matcher: "Bash", hooks: [{ type: "command", command: "./check.sh" }] };
const json = (v: unknown) => JSON.stringify(v, null, 2) + "\n";

test("hook command: in-tree CLI for the base-ai repository, the installed package elsewhere, never a bare base-ai", () => {
  assert.equal(isBaseAiRepo(JSON.stringify({ name: "@carlos17031691/base-ai" })), true);
  assert.equal(isBaseAiRepo(JSON.stringify({ name: "other" })), false);
  assert.equal(isBaseAiRepo("{not json"), false);
  assert.equal(isBaseAiRepo(null), false);
  assert.equal(hookCommand(true), 'node "$CLAUDE_PROJECT_DIR/cli/dist/index.js" usage record --root "$CLAUDE_PROJECT_DIR" # generated by base-ai');
  assert.equal(
    hookCommand(false),
    'node "$CLAUDE_PROJECT_DIR/node_modules/@carlos17031691/base-ai/dist/index.js" usage record --root "$CLAUDE_PROJECT_DIR" # generated by base-ai',
  );
  for (const c of [hookCommand(true), hookCommand(false)]) assert.doesNotMatch(c, /^base-ai /);
});

test("merge: a missing file or {} gets exactly the hooks key with one generated group per event", () => {
  const expected = json({ hooks: { SubagentStop: [gen()], Stop: [gen()] } });
  assert.equal(mergeHook(null, CMD), expected);
  assert.equal(mergeHook("{}", CMD), expected);
});

test("merge: user keys, a user Stop group and a user PreToolUse hook survive in order; one generated group appended", () => {
  const before = { permissions: { allow: ["Bash(ls)"] }, hooks: { PreToolUse: [userPre], Stop: [userStop] }, env: { A: "1" } };
  const after = JSON.parse(mergeHook(json(before), CMD));
  assert.deepEqual(Object.keys(after), ["permissions", "hooks", "env"]);
  assert.deepEqual(after.permissions, before.permissions);
  assert.deepEqual(after.env, before.env);
  assert.deepEqual(Object.keys(after.hooks), ["PreToolUse", "Stop", "SubagentStop"]);
  assert.deepEqual(after.hooks.PreToolUse, [userPre]);
  assert.deepEqual(after.hooks.Stop, [userStop, gen()]);
  assert.deepEqual(after.hooks.SubagentStop, [gen()]);
});

test("merge: an old generated command is replaced, not duplicated, and a second merge is a no-op", () => {
  const mixed = { hooks: { Stop: [{ hooks: [{ type: "command", command: "echo keep" }, { type: "command", command: OLD }] }], SubagentStop: [gen(OLD)] } };
  const once = mergeHook(json(mixed), CMD);
  const after = JSON.parse(once);
  assert.deepEqual(after.hooks.Stop, [{ hooks: [{ type: "command", command: "echo keep" }] }, gen()]);
  assert.deepEqual(after.hooks.SubagentStop, [gen()]);
  assert.equal(mergeHook(once, CMD), once);
});

test("removal: user entries intact, emptied containers dropped, delete only when a generated entry was removed", () => {
  const user = { permissions: { deny: [] }, hooks: { PreToolUse: [userPre], Stop: [userStop] } };
  const merged = mergeHook(json(user), CMD);
  assert.deepEqual(JSON.parse(removeHook(merged) as string), user);

  assert.equal(removeHook(mergeHook(null, CMD)), null, "only generated content: the file is deleted");
  assert.equal(removeHook("{}"), "{}", "nothing generated: unchanged, not deleted");
  assert.equal(removeHook(json(user)), json(user));
  assert.equal(removeHook(null), null);
  const noHooks = json({ hooks: {} });
  assert.equal(removeHook(noHooks), noHooks);
});

test("parseSettings refuses non-JSON, an array root, a non-object hooks and a non-array event", () => {
  for (const bad of ["{oops", "[]", '{"hooks": []}', '{"hooks": {"Stop": {}}}']) {
    assert.throws(() => parseSettings(bad), SettingsError, bad);
    assert.throws(() => mergeHook(bad, CMD), SettingsError, bad);
    assert.throws(() => removeHook(bad), SettingsError, bad);
  }
});

test("state: ok, missing, stale and invalid", () => {
  const merged = mergeHook(null, CMD);
  assert.equal(hookState(merged, "claude-code", CMD), "ok");
  assert.equal(hookState(null, "claude-code", CMD), "missing", "no file");
  assert.equal(hookState(json({ hooks: { Stop: [gen()] } }), "claude-code", CMD), "missing", "one event missing");
  assert.equal(hookState(json({ hooks: { Stop: [gen()], SubagentStop: [gen(OLD)] } }), "claude-code", CMD), "stale", "wrong command");
  assert.equal(hookState(json({ hooks: { Stop: [gen(), gen()], SubagentStop: [gen()] } }), "claude-code", CMD), "stale", "duplicate");
  assert.equal(hookState(json({ hooks: { Stop: [gen()], SubagentStop: [gen()], PreToolUse: [gen()] } }), "claude-code", CMD), "stale", "other event");
  assert.equal(hookState(merged, "none", CMD), "stale", "present while none");
  assert.equal(hookState(null, "none", CMD), "ok");
  assert.equal(hookState(json({ hooks: { Stop: [userStop] } }), "none", CMD), "ok");
  for (const bad of ["{oops", "[]", '{"hooks": 1}', '{"hooks": {"Stop": 1}}']) assert.equal(hookState(bad, "claude-code", CMD), "invalid", bad);
});
