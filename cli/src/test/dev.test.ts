import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { generateCompose, checkPrerequisites, devStop, devStatus } from "../dev.js";
import type { ComposeResult } from "../dev.js";

function makeDevProject(servicesYaml: string, services?: Record<string, { dockerfile?: boolean }>) {
  const root = mkdtempSync(join(tmpdir(), "base-ai-dev-"));
  writeFileSync(join(root, "services.yaml"), servicesYaml);
  if (services) {
    for (const [name, opts] of Object.entries(services)) {
      const svcDir = join(root, "src", name);
      mkdirSync(svcDir, { recursive: true });
      if (opts.dockerfile) {
        writeFileSync(join(svcDir, "Dockerfile"), "FROM node:20-alpine\nCMD [\"node\", \"index.js\"]");
      }
    }
  }
  return root;
}

function composeAndRead(yaml: string, svcs?: Record<string, { dockerfile?: boolean }>, filter?: string) {
  const root = makeDevProject(yaml, svcs);
  const result = generateCompose(root, filter);
  const content = existsSync(result.file) ? readFileSync(result.file, "utf8") : "";
  return { root, result, content };
}

const SINGLE_API = `services:\n  - name: api\n    repo: git@example.com:org/api.git`;
const TWO_SERVICES = `services:\n  - name: api\n    repo: git@example.com:org/api.git\n  - name: web\n    repo: git@example.com:org/web.git`;

test("creates docker-compose.dev.yml with services that have Dockerfiles", () => {
  const { result, content } = composeAndRead(TWO_SERVICES, { api: { dockerfile: true }, web: { dockerfile: true } });
  assert.equal(result.services.length, 2);
  assert.deepEqual(result.skipped, []);
  assert.ok(existsSync(result.file));
  assert.ok(content.includes("api"));
  assert.ok(content.includes("web"));
  assert.ok(content.startsWith("# Auto-generated by base-ai dev"));
});

test("skips services without Dockerfiles", () => {
  const yaml = `services:\n  - name: api\n    repo: git@example.com:org/api.git\n  - name: docs\n    repo: git@example.com:org/docs.git`;
  const { result } = composeAndRead(yaml, { api: { dockerfile: true }, docs: {} });
  assert.deepEqual(result.services, ["api"]);
  assert.deepEqual(result.skipped, ["docs"]);
});

test("filters by service name", () => {
  const { result } = composeAndRead(TWO_SERVICES, { api: { dockerfile: true }, web: { dockerfile: true } }, "api");
  assert.deepEqual(result.services, ["api"]);
});

test("throws for unknown service filter", () => {
  const root = makeDevProject(SINGLE_API, { api: { dockerfile: true } });
  assert.throws(() => generateCompose(root, "nonexistent"), /not found in services\.yaml/);
});

test("throws when services.yaml missing", () => {
  const root = mkdtempSync(join(tmpdir(), "base-ai-dev-"));
  assert.throws(() => generateCompose(root), /services\.yaml not found/);
});

test("respects dev.port override", () => {
  const yaml = `services:\n  - name: api\n    repo: git@example.com:org/api.git\n    dev:\n      port: 8080`;
  const { content } = composeAndRead(yaml, { api: { dockerfile: true } });
  assert.ok(content.includes("8080:3000"));
});

test("respects dev.env variables", () => {
  const yaml = `services:\n  - name: api\n    repo: git@example.com:org/api.git\n    dev:\n      env:\n        NODE_ENV: development\n        DEBUG: "true"`;
  const { content } = composeAndRead(yaml, { api: { dockerfile: true } });
  assert.ok(content.includes("NODE_ENV"));
  assert.ok(content.includes("development"));
  assert.ok(content.includes("DEBUG"));
});

test("includes infra services referenced by depends and excludes unreferenced", () => {
  const yaml = `services:\n  - name: api\n    repo: git@example.com:org/api.git\n    dev:\n      depends:\n        - redis\ndev:\n  infra:\n    redis:\n      image: redis:7-alpine\n      ports:\n        - "6379:6379"\n    postgres:\n      image: postgres:16-alpine\n      ports:\n        - "5432:5432"`;
  const { result, content } = composeAndRead(yaml, { api: { dockerfile: true } });
  assert.deepEqual(result.infra, ["redis"]);
  assert.ok(content.includes("redis:7-alpine"));
  assert.ok(!content.includes("postgres:16-alpine"), "unreferenced infra excluded");
});

test("respects dev.base_port", () => {
  const yaml = TWO_SERVICES + `\ndev:\n  base_port: 4000`;
  const { content } = composeAndRead(yaml, { api: { dockerfile: true }, web: { dockerfile: true } });
  assert.ok(content.includes("4000:3000"));
  assert.ok(content.includes("4001:3000"));
});

test("auto-increments ports for multiple services", () => {
  const yaml = `services:\n  - name: svc-a\n    repo: git@example.com:org/a.git\n  - name: svc-b\n    repo: git@example.com:org/b.git\n  - name: svc-c\n    repo: git@example.com:org/c.git`;
  const { content } = composeAndRead(yaml, { "svc-a": { dockerfile: true }, "svc-b": { dockerfile: true }, "svc-c": { dockerfile: true } });
  assert.ok(content.includes("3000:3000"));
  assert.ok(content.includes("3001:3000"));
  assert.ok(content.includes("3002:3000"));
});

test("creates .gitignore with .dev/ if none exists", () => {
  const { root } = composeAndRead(SINGLE_API, { api: { dockerfile: true } });
  assert.ok(readFileSync(join(root, ".gitignore"), "utf8").includes(".dev/"));
});

test("appends .dev/ to existing .gitignore", () => {
  const root = makeDevProject(SINGLE_API, { api: { dockerfile: true } });
  writeFileSync(join(root, ".gitignore"), "node_modules/\ndist/\n");
  generateCompose(root);
  const gitignore = readFileSync(join(root, ".gitignore"), "utf8");
  assert.ok(gitignore.includes("node_modules/"));
  assert.ok(gitignore.includes(".dev/"));
});

test("does not duplicate .dev/ in .gitignore", () => {
  const root = makeDevProject(SINGLE_API, { api: { dockerfile: true } });
  writeFileSync(join(root, ".gitignore"), "node_modules/\n.dev/\n");
  generateCompose(root);
  const lines = readFileSync(join(root, ".gitignore"), "utf8").split("\n").filter((l) => l.trim() === ".dev/");
  assert.equal(lines.length, 1);
});

test("checkPrerequisites returns structured result", () => {
  const result = checkPrerequisites();
  assert.equal(typeof result.ok, "boolean");
  if (!result.ok) assert.ok(result.error!.length > 0);
});

