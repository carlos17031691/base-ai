import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

/**
 * GateGuard facts:
 * 1. Callers: `npm test` via node:test runner; no runtime importers
 * 2. Tests `generateCompose`, `checkPrerequisites`, `devStop`, `devStatus` from `../dev.js`
 * 3. Data: reads/writes temp services.yaml, Dockerfiles, .gitignore; generates .dev/docker-compose.dev.yml
 * 4. User instruction: "adelante" (proceed with BASE-027 implementation)
 */

function makeDevProject(servicesYaml: string, services?: Record<string, { dockerfile?: boolean }>) {
  const root = mkdtempSync(join(tmpdir(), "base-ai-dev-"));
  writeFileSync(join(root, "services.yaml"), servicesYaml);
  if (services) {
    for (const [name, opts] of Object.entries(services)) {
      const svcDir = join(root, "src", name);
      mkdirSync(svcDir, { recursive: true });
      if (opts.dockerfile) {
        writeFileSync(join(svcDir, "Dockerfile"), "FROM node:20-alpine\nCMD [\"node\", \"index.js\"]");
      }
    }
  }
  return root;
}

test("generateCompose creates docker-compose.dev.yml with services that have Dockerfiles", async () => {
  const { generateCompose } = await import("../dev.js");
  const root = makeDevProject(
    `services:\n  - name: api\n    repo: git@example.com:org/api.git\n  - name: web\n    repo: git@example.com:org/web.git`,
    { api: { dockerfile: true }, web: { dockerfile: true } },
  );

  const result = generateCompose(root);
  assert.equal(result.services.length, 2);
  assert.deepEqual(result.skipped, []);
  assert.ok(existsSync(result.file));

  const content = readFileSync(result.file, "utf8");
  assert.ok(content.includes("api"));
  assert.ok(content.includes("web"));
  assert.ok(content.startsWith("# Auto-generated by base-ai dev"));
});

