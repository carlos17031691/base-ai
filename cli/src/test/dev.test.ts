test("sets volume mounts for hot reload", () => {
  const { content } = composeAndRead(SINGLE_API, { api: { dockerfile: true } });
  assert.ok(content.includes("../src/api:/app"));
});

test("sets PORT environment variable in compose", () => {
  const { content } = composeAndRead(SINGLE_API, { api: { dockerfile: true } });
  assert.ok(content.includes("PORT"));
  assert.ok(content.includes('"3000"'));
});

test("handles empty services list gracefully", () => {
  const { result } = composeAndRead(`services: []`);
  assert.deepEqual(result.services, []);
  assert.deepEqual(result.skipped, []);
});

test("creates .dev directory if it does not exist", () => {
  const root = makeDevProject(SINGLE_API, { api: { dockerfile: true } });
  assert.ok(!existsSync(join(root, ".dev")));
  generateCompose(root);
  assert.ok(existsSync(join(root, ".dev")));
});

test("rejects invalid service names (path traversal)", () => {
  const root = makeDevProject(
    `services:\n  - name: "../../etc"\n    repo: git@example.com:org/evil.git`,
    { "../../etc": { dockerfile: true } },
  );
  assert.throws(() => generateCompose(root), /Invalid service name/);
});

test("rejects invalid infra image references", () => {
  const yaml = `services:\n  - name: api\n    repo: git@example.com:org/api.git\n    dev:\n      depends:\n        - evil\ndev:\n  infra:\n    evil:\n      image: "EVIL IMAGE; rm -rf /"`;
  const root = makeDevProject(yaml, { api: { dockerfile: true } });
  assert.throws(() => generateCompose(root), /Invalid image reference/);
});

test("includes depends_on in compose output", () => {
  const yaml = `services:\n  - name: api\n    repo: git@example.com:org/api.git\n    dev:\n      depends:\n        - redis\ndev:\n  infra:\n    redis:\n      image: redis:7-alpine`;
  const { content } = composeAndRead(yaml, { api: { dockerfile: true } });
  assert.ok(content.includes("depends_on"));
  assert.ok(content.includes("redis"));
});
