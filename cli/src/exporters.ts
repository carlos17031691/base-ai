import type { Agent, AiSource, Skill } from "./source.js";

export interface OutFile {
  path: string;
  content: string;
}
export type Exporter = (src: AiSource) => OutFile[];

export const MARKER = "generated by base-ai";
/** Marker used by versions < 0.2 (Spanish). Still recognised so old artefacts can be replaced. */
export const LEGACY_MARKERS = ["generado por base-ai"];
export const isGenerated = (text: string) => [MARKER, ...LEGACY_MARKERS].some((m) => text.includes(m));
const HEADER = `<!-- ${MARKER}: do not edit. Source: .ai/ -->`;
/** Header of the role definitions exported to services: their source is the root's .claude/agents/, not .ai/. */
export const AGENT_HEADER = `<!-- ${MARKER}: do not edit. Source: root .claude/agents/ -->`;

/** Builds a Markdown file with the "generated" header; with frontmatter, the header goes right after it. */
function md(path: string, body: string, frontmatter?: Record<string, string | boolean>): OutFile {
  const fm = frontmatter
    ? `---\n${Object.entries(frontmatter)
        .map(([k, v]) => `${k}: ${typeof v === "string" ? JSON.stringify(v) : v}`)
        .join("\n")}\n---\n`
    : "";
  return { path, content: `${fm}${HEADER}\n\n${body.trim()}\n` };
}

const forAgent = (src: AiSource, a: Agent): Skill[] => src.skills.filter((s) => s.targets.includes(a));

function skillIndex(skills: Skill[]): string {
  if (!skills.length) return "";
  return `\n\n## Available skills\n\n${skills.map((s) => `- **${s.id}**: ${s.description}`).join("\n")}`;
}

/**
 * The rules as CLAUDE.md carries them (BASE-079-T5): without the `## Available agents` section, from that heading to
 * the next `## ` heading or the end. Claude Code lists agents (`.claude/agents/`) and skills (`.claude/commands/`)
 * natively, so CLAUDE.md also gets no skill index. Rules without the section are returned unchanged.
 */
export function claudeRules(rules: string): string {
  const start = rules.search(/^## Available agents[ \t]*$/m);
  if (start === -1) return rules;
  const heading = "## Available agents";
  const rest = rules.slice(start + heading.length);
  const next = rest.search(/^## /m);
  const tail = next === -1 ? "" : rest.slice(next);
  return [rules.slice(0, start).trimEnd(), tail].filter(Boolean).join("\n\n");
}

/** AGENTS.md is shared by Antigravity and Codex. */
const agentsMd = (src: AiSource, a: Agent) => md("AGENTS.md", src.rules + skillIndex(forAgent(src, a)));

export const exporters: Record<Agent, Exporter> = {
  antigravity: (src) => [
    agentsMd(src, "antigravity"),
    ...forAgent(src, "antigravity").map((s) =>
      md(`.agents/skills/${s.id}/SKILL.md`, s.body, { name: s.id, description: s.description }),
    ),
  ],
  codex: (src) => [agentsMd(src, "codex")],
  claude: (src) => [
    md("CLAUDE.md", claudeRules(src.rules)),
    ...forAgent(src, "claude").map((s) => md(`.claude/commands/${s.id}.md`, s.body, { description: s.description })),
    // Frontmatter kept byte for byte (Claude Code parses it), then the header after it.
    ...src.roles.flatMap((r) => [
      { path: `.claude/agents/${r.id}.md`, content: `${r.frontmatter}${AGENT_HEADER}\n\n${r.body.trim()}\n` },
      // Reference files have no frontmatter: the header comes first.
      ...r.references.map((ref) => ({
        path: `.claude/agents/${r.id}/${ref.name}`,
        content: `${AGENT_HEADER}\n\n${ref.body.trim()}\n`,
      })),
    ]),
  ],
  cursor: (src) => [
    md(".cursor/rules/base-ai.mdc", src.rules, { description: "Global project rules", alwaysApply: true }),
    ...forAgent(src, "cursor").map((s) =>
      md(`.cursor/rules/${s.id}.mdc`, s.body, { description: s.description, alwaysApply: false }),
    ),
  ],
  copilot: (src) => [
    md(".github/copilot-instructions.md", src.rules + skillIndex(forAgent(src, "copilot"))),
    ...forAgent(src, "copilot").map((s) =>
      md(`.github/prompts/${s.id}.prompt.md`, s.body, { description: s.description }),
    ),
  ],
};

/** Runs the enabled exporters; files produced by several exporters at the same path are merged. */
export function render(src: AiSource): OutFile[] {
  const out = new Map<string, string>();
  for (const a of src.agents) {
    for (const f of exporters[a](src)) {
      const prev = out.get(f.path);
      if (prev !== undefined && prev !== f.content) {
        // Shared AGENTS.md: keep the longest (union of skill index; antigravity/codex usually match).
        if (f.content.length > prev.length) out.set(f.path, f.content);
        continue;
      }
      out.set(f.path, f.content);
    }
  }
  return [...out.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([path, content]) => ({ path, content }));
}
