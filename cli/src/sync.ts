import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { parse } from "yaml";
import { buildContextIndex } from "./context.js";
import { isGenerated, render } from "./exporters.js";
import { loadRoleDefinitions, loadSource, mergeSource, type AiSource } from "./source.js";
import {
  SETTINGS_PATH,
  SettingsError,
  hookCommand,
  hookState,
  isBaseAiRepo,
  mergeHook,
  removeHook,
  type HookState,
  type UsageHook,
} from "./usage-hook.js";

const LOCK = ".ai/generated.json";

export interface SyncResult {
  target: string;
  written: string[];
  removed: string[];
  unchanged: string[];
}

function readLock(dir: string): string[] {
  const p = join(dir, LOCK);
  return existsSync(p) ? (JSON.parse(readFileSync(p, "utf8")) as { files: string[] }).files : [];
}

/** Writes (or, with check=true, only compares) the artefacts of a directory. Idempotent. */
export function syncDir(dir: string, src: AiSource, check: boolean): SyncResult {
  const files = render(src);
  const res: SyncResult = { target: dir, written: [], removed: [], unchanged: [] };
  const produced = new Set(files.map((f) => f.path));

  for (const f of files) {
    const abs = join(dir, f.path);
    if (existsSync(abs)) {
      const current = readFileSync(abs, "utf8");
      if (current === f.content) {
        res.unchanged.push(f.path);
        continue;
      }
      if (!isGenerated(current)) {
        if (f.path.startsWith(".claude/agents/")) {
          throw new Error(
            `${abs} exists and was not generated by base-ai; delete it: agent definitions are exported from the root .claude/agents/`,
          );
        }
        throw new Error(`${abs} exists and was not generated by base-ai; move it into .ai/ or delete it`);
      }
    }
    res.written.push(f.path);
    if (!check) {
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, f.content);
    }
  }

  // Delete stale artefacts (removed skill or agent) that still carry the marker.
  for (const old of readLock(dir)) {
    if (produced.has(old)) continue;
    const abs = join(dir, old);
    if (existsSync(abs) && isGenerated(readFileSync(abs, "utf8"))) {
      res.removed.push(old);
      if (!check) rmSync(abs);
    }
  }

  if (!check) {
    mkdirSync(join(dir, ".ai"), { recursive: true });
    writeFileSync(join(dir, LOCK), JSON.stringify({ files: [...produced] }, null, 2) + "\n");
  }
  return res;
}

const readText = (abs: string) => (existsSync(abs) ? readFileSync(abs, "utf8") : null);

/** The hook command for this root (H1): in-tree CLI in the base-ai repository, else the installed package. */
export const usageHookCommand = (root: string) => hookCommand(isBaseAiRepo(readText(join(root, "cli", "package.json"))));

/** The doctor's state of the root's `.claude/settings.json` for the configured hook. */
export function usageHookState(root: string, hook: UsageHook): HookState {
  return hookState(readText(join(root, SETTINGS_PATH)), hook, usageHookCommand(root));
}

/**
 * Writes or removes the generated usage hook in the root's `.claude/settings.json` (BASE-101-U2), keeping every
 * user key. The file is reported in `res` but never added to the lock. An invalid file throws and nothing is
 * written; with check=true it is only reported as out of date, and the doctor names the problem.
 */
export function syncUsageHook(root: string, hook: UsageHook, check: boolean, res: SyncResult): void {
  const abs = join(root, SETTINGS_PATH);
  const current = readText(abs);
  let next: string | null;
  try {
    next = hook === "claude-code" ? mergeHook(current, usageHookCommand(root)) : removeHook(current);
  } catch (e) {
    if (!(e instanceof SettingsError)) throw e;
    if (check) {
      res.written.push(SETTINGS_PATH);
      return;
    }
    throw new Error(`${abs} ${e.message}; fix it, then run: base-ai ai sync`);
  }
  if (next === current) {
    if (current !== null && hook === "claude-code") res.unchanged.push(SETTINGS_PATH);
    return;
  }
  if (next === null) {
    res.removed.push(SETTINGS_PATH);
    if (!check) rmSync(abs);
    return;
  }
  (hook === "claude-code" ? res.written : res.removed).push(SETTINGS_PATH);
  if (!check) {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, next);
  }
}

interface ServiceEntry {
  name: string;
  ai?: "inherit" | "none";
}

/** ai sync: root + services with ai: inherit present in src/. */
export function aiSync(root: string, check = false): SyncResult[] {
  const base = loadSource(root);
  const results = [syncDir(root, base, check)];
  // Services keep their own settings: the hook is written at the root only (H7).
  syncUsageHook(root, base.usageHook ?? "none", check, results[0]);

  const manifest = join(root, "services.yaml");
  if (!existsSync(manifest)) return results;
  const services = ((parse(readFileSync(manifest, "utf8")) ?? {}).services ?? []) as ServiceEntry[];
  // The root's hand-written role definitions are exported to services only (ADR-0004).
  const roles = loadRoleDefinitions(root);

  for (const s of services) {
    if (s.ai === "none") continue;
    const dir = join(root, "src", s.name);
    if (!existsSync(dir)) continue; // not cloned yet: run `base-ai sync`
    const local = existsSync(join(dir, ".ai")) ? loadSource(dir) : null;
    results.push(syncDir(dir, { ...mergeSource(base, local), roles }, check));
  }
  if (!check) buildContextIndex(root);
  return results;
}
