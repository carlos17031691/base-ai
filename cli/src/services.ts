import { execFileSync } from "node:child_process";
import { chmodSync, cpSync, existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { isMap, isSeq, parseDocument, YAMLSeq } from "yaml";
import { aiSync } from "./sync.js";

export const CLOUD_PROVIDERS = ["aws", "gcp", "azure", "cloudflare", "fly", "k8s", "custom"] as const;
export type CloudProvider = (typeof CLOUD_PROVIDERS)[number];

export const IAC_TOOLS = ["terraform", "opentofu", "pulumi", "cdk", "docker", "none"] as const;
export type IacTool = (typeof IAC_TOOLS)[number];

export interface Service {
  name: string;
  repo: string;
  /** Omitted = the remote's default branch. */
  branch?: string;
  cloud?: CloudProvider;
  iac?: IacTool;
  template?: string;
  ai?: "inherit" | "none";
}

const NAME_RE = /^[a-z0-9-]+$/;
const BRANCH_RE = /^[A-Za-z0-9._/-]+$/;
const manifestPath = (root: string) => join(root, "services.yaml");

const PRE_COMMIT_HOOK = `#!/bin/sh
# generated by base-ai: do not edit.
# Blocks commits on protected branches and requires a Story/Epic/Task ID in the branch name.
# Allows only the initial root commit when the repository has no commits yet.

if ! git rev-parse --verify HEAD >/dev/null 2>&1; then
  exit 0
fi

branch="$(git symbolic-ref --short -q HEAD 2>/dev/null || true)"

case "$branch" in
  ""|main|master|development)
    echo "✖ [base-ai] Direct commits on '\${branch:-detached HEAD}' are forbidden." >&2
    echo "  Create a working branch linked to a Story/Epic/Task first, e.g.:" >&2
    echo "    git checkout -b feat/PROJ-123-short-description" >&2
    exit 1
    ;;
esac

if ! printf '%s\\n' "$branch" | grep -Eq '([A-Za-z]{2,}[0-9]*-[0-9]+|[Cc][Uu]-[0-9A-Za-z]*[0-9][0-9A-Za-z]*|(^|[/_#-])[0-9]{2,}([-_/]|$))'; then
  echo "✖ [base-ai] Branch '$branch' must include a Story/Epic/Task ID (Jira/ClickUp/Trello/etc.)." >&2
  echo "  Examples: feat/PROJ-123-add-auth, fix/CU-86a1b2-timeout, chore/TASK-42-deps" >&2
  exit 1
fi
`;

const COMMIT_MSG_HOOK = `#!/bin/sh
# generated by base-ai: do not edit.
# Requires a Story/Epic/Task ID (Jira/ClickUp/Trello/etc.) in every commit message.
# Allows the initial root commit when the repository has no commits yet.

if ! git rev-parse --verify HEAD >/dev/null 2>&1; then
  exit 0
fi

msg_file="$1"
first_line="$(grep -v '^[[:space:]]*#' "$msg_file" | head -n 1)"

if ! printf '%s\\n' "$first_line" | grep -Eq '([A-Za-z]{2,}[0-9]*-[0-9]+|[Cc][Uu]-[0-9A-Za-z]*[0-9][0-9A-Za-z]*|#[0-9]+)'; then
  echo "✖ [base-ai] Commit message must reference a Story/Epic/Task ID (e.g. PROJ-123, CU-86a1b2, #45)." >&2
  echo "  Example: feat(PROJ-123): handle duplicate webhook events" >&2
  exit 1
fi
`;

const ZERO_SHA = "0000000000000000000000000000000000000000";

const PRE_PUSH_HOOK = `#!/bin/sh
# generated by base-ai: do not edit.
# Blocks direct pushes to protected branches (main, master, development); changes must go through a PR.
# Allows only the single initial scaffold commit (commit count == 1) when bootstrapping an empty remote branch.

ZERO_SHA="${ZERO_SHA}"

while read -r local_ref local_sha remote_ref remote_sha; do
  case "$remote_ref" in
    refs/heads/main|refs/heads/master|refs/heads/development)
      commit_count="$(git rev-list --count "$local_sha" 2>/dev/null || echo 999)"
      if [ "$remote_sha" = "$ZERO_SHA" ] && [ "$commit_count" = "1" ]; then
        continue
      fi
      echo "✖ [base-ai] Direct push to '\${remote_ref#refs/heads/}' is forbidden." >&2
      echo "  Push your working branch and open a Pull Request instead:" >&2
      echo "    git push -u origin HEAD" >&2
      exit 1
      ;;
  esac
done
`;

function git(args: string[], cwd?: string): string {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

function validateName(name: string | undefined): string {
  if (!name || !NAME_RE.test(name)) throw new Error(`Invalid service name "${name ?? ""}" (must match ^[a-z0-9-]+$)`);
  return name;
}

function validateRepo(repo: string | undefined): string {
  if (!repo || repo.startsWith("-")) throw new Error(`Invalid repository URL "${repo ?? ""}" (every service requires a remote repository)`);
  return repo;
}

function validateBranch(branch: string | undefined): string | undefined {
  if (branch !== undefined && (branch.startsWith("-") || !BRANCH_RE.test(branch))) throw new Error(`Invalid branch "${branch}"`);
  return branch;
}

function validateCloud(cloud: string | undefined): CloudProvider | undefined {
  if (cloud !== undefined && !CLOUD_PROVIDERS.includes(cloud as CloudProvider)) {
    throw new Error(`Invalid cloud provider "${cloud}" (${CLOUD_PROVIDERS.join(" | ")})`);
  }
  return cloud as CloudProvider | undefined;
}

function validateIac(iac: string | undefined): IacTool | undefined {
  if (iac !== undefined && !IAC_TOOLS.includes(iac as IacTool)) {
    throw new Error(`Invalid IaC tool "${iac}" (${IAC_TOOLS.join(" | ")})`);
  }
  return iac as IacTool | undefined;
}

function scaffoldCloudInfra(dest: string, name: string, cloud?: CloudProvider, iac?: IacTool): void {
  if (!cloud && (!iac || iac === "none")) return;
  for (const sub of ["modules", "staging", "production"]) {
    const d = join(dest, "infrastructure", sub);
    mkdirSync(d, { recursive: true });
    writeFileSync(join(d, ".gitkeep"), "");
  }
  const provider = cloud ?? "cloud provider";
  const tool = iac && iac !== "none" ? iac : "IaC";
  const readme = `# Infrastructure — ${name} (${provider} / ${tool})

Provisioned and monitored as code (see \`infrastructure\` and \`observability\` skills).

## Layout

- \`modules/\` — reusable compute, data, messaging and monitoring modules
- \`staging/\` — pre-production environment composition & remote state
- \`production/\` — production environment composition & remote state

## Security & GitOps Checklist

- [ ] **Keyless OIDC auth:** CI authenticates to \`${provider}\` via OIDC federation (zero static cloud keys in Git/CI).
- [ ] **Remote state with locking:** encrypted remote backend configured; \`*.tfstate\` / \`*.tfplan\` are git-ignored.
- [ ] **Mandatory resource tags:** \`service=${name}\`, \`env=staging|production\`, \`managed_by=${tool}\`.
- [ ] **PR Plan → Merge Apply:** every PR runs \`fmt\`, \`validate\`, IaC security scan and posts the execution \`plan\`.
- [ ] **Monitoring as Code:** alarms provisioned alongside resources (compute saturation/restarts, DB connections/storage/replication, queue age & \`DLQ > 0\`, 5xx rate, and monthly Cloud FinOps budget alerts at 50/80/100%).
`;
  writeFileSync(join(dest, "infrastructure", "README.md"), readme);
}

/** Writes .githooks scripts (pre-commit, commit-msg, pre-push) into a repository without activating core.hooksPath yet. */
export function writeServiceHooks(dest: string): void {
  const hooksDir = join(dest, ".githooks");
  mkdirSync(hooksDir, { recursive: true });
  const hooks: Record<string, string> = {
    "pre-commit": PRE_COMMIT_HOOK,
    "commit-msg": COMMIT_MSG_HOOK,
    "pre-push": PRE_PUSH_HOOK,
  };
  for (const [name, content] of Object.entries(hooks)) {
    const p = join(hooksDir, name);
    writeFileSync(p, content);
    chmodSync(p, 0o755);
  }
}

/** Activates .githooks as core.hooksPath on an initialised Git repository. */
export function activateServiceHooks(dest: string): void {
  if (existsSync(join(dest, ".git"))) {
    git(["config", "core.hooksPath", ".githooks"], dest);
  }
}

/** Installs and activates .githooks (branch, ticket and PR-only rules) in a repository. */
export function installServiceHooks(dest: string): void {
  writeServiceHooks(dest);
  activateServiceHooks(dest);
}

/**
 * Bootstraps a clean Git repository with an initial baseline commit on `main`,
 * creates and switches to `development`, and only then activates `.githooks`
 * so `main` and `development` exist from second zero without ever bypassing hooks later.
 */
export function bootstrapGitBaseline(dest: string, message: string, remoteUrl?: string): void {
  git(["init", "-q", "-b", "main"], dest);
  if (remoteUrl) {
    git(["remote", "add", "origin", remoteUrl], dest);
  }
  git(["add", "."], dest);
  git(
    ["-c", "user.name=base-ai", "-c", "user.email=base-ai@local", "commit", "-q", "-m", message],
    dest,
  );
  git(["checkout", "-q", "-b", "development"], dest);
  if (remoteUrl && existsSync(remoteUrl)) {
    try {
      git(["push", "-q", "-u", "origin", "main", "development"], dest);
    } catch {
      // Non-bare or unreachable remote in unit tests; ignore.
    }
  }
  activateServiceHooks(dest);
}

/** Reads services.yaml preserving comments. */
function loadDoc(root: string) {
  const p = manifestPath(root);
  const doc = parseDocument(existsSync(p) ? readFileSync(p, "utf8") : "version: 1\nservices: []\n");
  let seq = doc.get("services");
  if (!isSeq(seq)) {
    seq = new YAMLSeq();
    doc.set("services", seq);
  }
  return { doc, seq: seq as YAMLSeq };
}

export function listServices(root: string): Service[] {
  const list = (loadDoc(root).seq.toJSON() as Service[]) ?? [];
  for (const s of list) {
    validateName(s.name);
    validateRepo(s.repo);
    validateBranch(s.branch);
    validateCloud(s.cloud);
    validateIac(s.iac);
  }
  return list;
}

function addEntry(root: string, svc: Service): void {
  const { doc, seq } = loadDoc(root);
  if (seq.items.some((i) => isMap(i) && i.get("name") === svc.name)) throw new Error(`Service "${svc.name}" already exists in services.yaml`);
  seq.flow = false;
  seq.add(doc.createNode(Object.fromEntries(Object.entries(svc).filter(([, v]) => v !== undefined))));
  writeFileSync(manifestPath(root), doc.toString());
}

/** Replaces {{name}} in the content of the copied template files and restores `_gitignore` → `.gitignore`. */
function renderTemplate(dir: string, name: string): void {
  for (const entry of readdirSync(dir)) {
    const abs = join(dir, entry);
    if (statSync(abs).isDirectory()) {
      renderTemplate(abs, name);
      continue;
    }
    const target = entry === "_gitignore" ? join(dir, ".gitignore") : abs;
    if (target !== abs) renameSync(abs, target);
    const text = readFileSync(target, "utf8");
    if (text.includes("{{name}}")) writeFileSync(target, text.replaceAll("{{name}}", name));
  }
}

export interface ServiceNewOptions {
  template?: string;
  cloud?: string;
  iac?: string;
}

/** service new: creates src/<name> from templates/<template>, sets origin <repo>, activates git hooks and registers it. */
export function serviceNew(
  root: string,
  rawName: string | undefined,
  rawRepo: string | undefined,
  templateOrOpts: string | ServiceNewOptions = "service",
): string {
  const opts: ServiceNewOptions = typeof templateOrOpts === "string" ? { template: templateOrOpts } : templateOrOpts;
  const template = opts.template ?? "service";
  const cloud = validateCloud(opts.cloud);
  const iac = validateIac(opts.iac);
  const name = validateName(rawName);
  const repo = validateRepo(rawRepo);
  const tpl = join(root, "templates", validateName(template));
  const dest = join(root, "src", name);
  if (!existsSync(tpl)) throw new Error(`Template not found: ${tpl}`);
  if (existsSync(dest)) throw new Error(`${dest} already exists`);

  addEntry(root, { name, repo, cloud, iac, template, ai: "inherit" });
  cpSync(tpl, dest, { recursive: true });
  renderTemplate(dest, name);
  scaffoldCloudInfra(dest, name, cloud, iac);
  writeServiceHooks(dest);
  aiSync(root);
  bootstrapGitBaseline(dest, "chore: initial base-ai service scaffold", repo);
  return dest;
}

/** service add: registers an existing repo, clones it and activates git hooks. */
export function serviceAdd(root: string, rawName: string | undefined, rawRepo: string | undefined, branch?: string): string {
  const name = validateName(rawName);
  const repo = validateRepo(rawRepo);
  addEntry(root, { name, repo, branch: validateBranch(branch), ai: "inherit" });
  syncServices(root);
  return join(root, "src", name);
}

/** service remove: drops it from the manifest; with purge, deletes src/<name> only if it has no uncommitted changes. */
export function serviceRemove(root: string, rawName: string | undefined, purge = false): void {
  const name = validateName(rawName);
  const { doc, seq } = loadDoc(root);
  const idx = seq.items.findIndex((i) => isMap(i) && i.get("name") === name);
  if (idx < 0) throw new Error(`Service "${name}" is not in services.yaml`);
  const dest = join(root, "src", name);
  if (purge && existsSync(dest)) {
    if (git(["status", "--porcelain"], dest)) throw new Error(`${dest} has uncommitted changes; not deleting`);
    rmSync(dest, { recursive: true, force: true });
  }
  seq.items.splice(idx, 1);
  writeFileSync(manifestPath(root), doc.toString());
}

export interface ServiceSyncResult {
  name: string;
  action: "cloned" | "updated" | "skipped";
  reason?: string;
}

/** sync: clones what is missing, fast-forwards what exists and ensures git hooks & AI artefacts are in place. Idempotent. */
export function syncServices(root: string): ServiceSyncResult[] {
  const results: ServiceSyncResult[] = [];
  for (const s of listServices(root)) {
    const name = validateName(s.name);
    const repo = validateRepo(s.repo);
    const branch = validateBranch(s.branch);
    const dest = join(root, "src", name);
    if (!existsSync(dest)) {
      git(["clone", "-q", ...(branch ? ["-b", branch] : []), "--", repo, dest]);
      installServiceHooks(dest);
      results.push({ name, action: "cloned" });
      continue;
    }
    installServiceHooks(dest);
    // Only tracked files count: untracked AI/hook artefacts must not block updates.
    if (git(["status", "--porcelain", "--untracked-files=no"], dest)) {
      results.push({ name, action: "skipped", reason: "uncommitted local changes" });
      continue;
    }
    try {
      git(["pull", "-q", "--ff-only", ...(branch ? ["origin", branch] : [])], dest);
      results.push({ name, action: "updated" });
    } catch (e) {
      results.push({ name, action: "skipped", reason: `pull failed: ${(e as Error).message.split("\n")[0]}` });
    }
  }
  aiSync(root);
  return results;
}
