import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";
import { stringify, parse } from "yaml";
import type { Service } from "./services.js";

// ── Types ──────────────────────────────────────────────────────────────

export interface DevServiceConfig {
  port?: number;
  env?: Record<string, string>;
  depends?: string[];
}

export interface DevInfraService {
  image: string;
  environment?: Record<string, string>;
  ports?: string[];
  volumes?: string[];
}

export interface DevConfig {
  base_port?: number;
  infra?: Record<string, DevInfraService>;
}

interface ServiceWithDev extends Service {
  dev?: DevServiceConfig;
}

interface ManifestWithDev {
  services?: ServiceWithDev[];
  dev?: DevConfig;
}

// ── Constants ──────────────────────────────────────────────────────────

const DEV_DIR = ".dev";
const COMPOSE_FILE = "docker-compose.dev.yml";
const DEFAULT_BASE_PORT = 3000;
const CONTAINER_PORT = 3000;
const SERVICE_NAME_RE = /^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/;
const IMAGE_RE = /^[a-z0-9]([a-z0-9._/-]{0,200}[a-z0-9])?(:[a-zA-Z0-9._-]{1,128})?(@sha256:[a-f0-9]{64})?$/;

// ── Compose generation ─────────────────────────────────────────────────

export interface ComposeResult {
  file: string;
  services: string[];
  skipped: string[];
  infra: string[];
}

export function generateCompose(root: string, serviceFilter?: string): ComposeResult {
  const manifest = loadManifestWithDev(root);
  const allServices = manifest.services ?? [];
  const devConfig = manifest.dev ?? {};
  const basePort = devConfig.base_port ?? DEFAULT_BASE_PORT;

  const filtered = serviceFilter
    ? allServices.filter((s) => s.name === serviceFilter)
    : allServices;

  if (filtered.length === 0 && serviceFilter) {
    throw new Error(`Service "${serviceFilter}" not found in services.yaml`);
  }

  const composeServices: Record<string, unknown> = {};
  const included: string[] = [];
  const skipped: string[] = [];
  const requiredInfra = new Set<string>();
  let nextPort = basePort;

  for (const svc of filtered) {
    if (!SERVICE_NAME_RE.test(svc.name)) {
      throw new Error(`Invalid service name "${svc.name}" — must be lowercase alphanumeric with hyphens`);
    }
    const svcDir = join(root, "src", svc.name);
    const dockerfile = join(svcDir, "Dockerfile");

    if (!existsSync(dockerfile)) {
      skipped.push(svc.name);
      continue;
    }

    const hostPort = svc.dev?.port ?? nextPort++;
    const env: Record<string, string> = { PORT: String(CONTAINER_PORT), ...svc.dev?.env };

    composeServices[svc.name] = {
      build: { context: `../src/${svc.name}`, dockerfile: "Dockerfile" },
      ports: [`${hostPort}:${CONTAINER_PORT}`],
      volumes: [`../src/${svc.name}:/app`],
      environment: env,
      ...(svc.dev?.depends?.length ? { depends_on: svc.dev.depends } : {}),
    };

    included.push(svc.name);
    for (const dep of svc.dev?.depends ?? []) requiredInfra.add(dep);
  }

  const infraServices: string[] = [];
  if (devConfig.infra) {
    for (const [name, config] of Object.entries(devConfig.infra)) {
      if (!requiredInfra.has(name)) continue;
      if (!IMAGE_RE.test(config.image)) {
        throw new Error(`Invalid image reference "${config.image}" for infra service "${name}"`);
      }
      composeServices[name] = {
        image: config.image,
        ...(config.environment ? { environment: config.environment } : {}),
        ...(config.ports?.length ? { ports: config.ports } : {}),
        ...(config.volumes?.length ? { volumes: config.volumes } : {}),
      };
      infraServices.push(name);
    }
  }

  const compose = { services: composeServices };
  const header = "# Auto-generated by base-ai dev — do not edit\n";
  const yaml = header + stringify(compose, { lineWidth: 120 });

  const devDir = join(root, DEV_DIR);
  if (!existsSync(devDir)) mkdirSync(devDir, { recursive: true });
  const filePath = join(devDir, COMPOSE_FILE);
  writeFileSync(filePath, yaml);

  ensureGitignore(root);

  return { file: filePath, services: included, skipped, infra: infraServices };
}

function loadManifestWithDev(root: string): ManifestWithDev {
  const manifestPath = join(root, "services.yaml");
  if (!existsSync(manifestPath)) throw new Error("services.yaml not found — run base-ai init first");
  return (parse(readFileSync(manifestPath, "utf8"), { schema: "core" }) ?? {}) as ManifestWithDev;
}

function ensureGitignore(root: string): void {
  const gitignorePath = join(root, ".gitignore");
  if (!existsSync(gitignorePath)) {
    writeFileSync(gitignorePath, ".dev/\n");
    return;
  }
  const content = readFileSync(gitignorePath, "utf8");
  if (content.split("\n").some((line) => line.trim() === ".dev/" || line.trim() === ".dev")) return;
  writeFileSync(gitignorePath, content.trimEnd() + "\n.dev/\n");
}

// ── Prerequisites ──────────────────────────────────────────────────────

export function checkPrerequisites(): { ok: boolean; error?: string } {
  try {
    execFileSync("docker", ["--version"], { stdio: "pipe" });
  } catch {
    return { ok: false, error: "docker not found — install Docker to use base-ai dev" };
  }
  try {
    const version = execFileSync("docker", ["compose", "version", "--short"], { stdio: "pipe" }).toString().trim();
    const major = parseInt(version.replace(/^v/, "").split(".")[0], 10);
    if (isNaN(major) || major < 2) {
      return { ok: false, error: `Docker Compose v2+ required (found ${version})` };
    }
  } catch {
    return { ok: false, error: "docker compose not found — install Docker Compose v2+" };
  }
  return { ok: true };
}

// ── Lifecycle commands ─────────────────────────────────────────────────

export function devUp(root: string, serviceFilter?: string): ComposeResult {
  const prereq = checkPrerequisites();
  if (!prereq.ok) throw new Error(prereq.error!);

  const result = generateCompose(root, serviceFilter);

  if (result.services.length === 0) {
    throw new Error("No services with Dockerfiles found — nothing to start");
  }

  execFileSync("docker", ["compose", "-f", result.file, "up", "-d", "--build"], {
    stdio: "inherit",
    cwd: root,
  });

  return result;
}

export function devStop(root: string): void {
  const composePath = join(root, DEV_DIR, COMPOSE_FILE);
  if (!existsSync(composePath)) throw new Error("No dev stack found — run base-ai dev first");

  execFileSync("docker", ["compose", "-f", composePath, "down"], {
    stdio: "inherit",
    cwd: root,
  });
}

export function devStatus(root: string): string {
  const composePath = join(root, DEV_DIR, COMPOSE_FILE);
  if (!existsSync(composePath)) throw new Error("No dev stack found — run base-ai dev first");

  return execFileSync("docker", ["compose", "-f", composePath, "ps"], {
    cwd: root,
    encoding: "utf8",
  });
}
